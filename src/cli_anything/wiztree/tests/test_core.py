def _blind(monkeypatch):
    """Isolate discovery from this machine: no env, registry, config or PATH hit."""
    monkeypatch.delenv(wb.ENV_VAR, raising=False)
    monkeypatch.setattr(wb, "DEFAULT_SEARCH_PATHS", ())
    monkeypatch.setattr(wb, "_registry_candidates", lambda: [])
    monkeypatch.setattr(wb, "_config_candidates", lambda: [])
    monkeypatch.setattr(wb, "_env_candidates", lambda: [])
    monkeypatch.setattr(wb.shutil, "which", lambda name: None)


