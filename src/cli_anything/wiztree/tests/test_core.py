class TestParseExportCsv:

    def test_parses_chinese_header_positionally(self, tmp_path):
        entries, meta = index.parse_export_csv(_write(tmp_path, "zh.csv", CSV_ZH_WITH_CAPACITY))
        assert len(entries) == 4
        root = entries[0]
        assert root.name == "D:\\sample\\"
        assert root.size == 1000
        assert root.allocated == 1024
        assert root.files == 3
        assert root.folders == 2
        assert root.modified == "2026/09/27 11:53:56"
        assert root.attributes == 0

    def test_parses_english_header_positionally(self, tmp_path):
        entries, meta = index.parse_export_csv(_write(tmp_path, "en.csv", CSV_EN_PLAIN))
        assert len(entries) == 4
        assert entries[0].size == 3000
        assert entries[1].name == "C:\\test\\a.mp3"

    def test_banner_line_is_skipped(self, tmp_path):
        entries, meta = index.parse_export_csv(_write(tmp_path, "zh.csv", CSV_ZH_WITH_CAPACITY))
        assert all("WizTree 4.27" not in e.name for e in entries)
        assert meta["banner"] == BANNER_ZH

    def test_capacity_columns_do_not_shift_positional_fields(self, tmp_path):
        """F3 regression: 11-column and 7-column files must parse identically."""
        zh, _ = index.parse_export_csv(_write(tmp_path, "zh.csv", CSV_ZH_WITH_CAPACITY))
        en, _ = index.parse_export_csv(_write(tmp_path, "en.csv", CSV_EN_PLAIN))
        assert [e.size for e in zh[:2]] == [1000, 500]
        assert [e.size for e in en[:2]] == [3000, 1500]
        # extra columns land in `extra`, never in core fields
        assert zh[0].extra.get("DRIVECAPACITY") == "364242792448"
        assert en[0].extra == {}

    def test_quoted_name_containing_comma(self, tmp_path):
        entries, _ = index.parse_export_csv(_write(tmp_path, "zh.csv", CSV_ZH_WITH_CAPACITY))
        assert entries[3].name == "D:\\sample\\big, with comma.bin"

    def test_ragged_row_is_padded_not_crashed(self, tmp_path):
        text = "\n".join([
            BANNER_EN,
            "File Name,Size,Allocated,Modified,Attributes,Files,Folders",
            '"C:\\x\\",10,10,2026/09/27 11:53:56,0,1,1',
            '"C:\\x\\weird",20,20',
        ])
        entries, _ = index.parse_export_csv(_write(tmp_path, "ragged.csv", text))
        assert len(entries) == 2
        assert entries[1].modified == ""
        assert entries[1].files == 0

    def test_junk_rows_without_numeric_size_are_skipped(self, tmp_path):
        text = "\n".join([
            BANNER_EN,
            "File Name,Size,Allocated,Modified,Attributes,Files,Folders",
            "some trailing note,alpha,beta,gamma,delta,epsilon,zeta",
            '"C:\\x\\",10,10,2026/09/27 11:53:56,0,1,1',
        ])
        entries, _ = index.parse_export_csv(_write(tmp_path, "junk.csv", text))
        assert len(entries) == 1
        assert entries[0].name == "C:\\x\\"

    def test_empty_file_yields_no_entries(self, tmp_path):
        entries, meta = index.parse_export_csv(_write(tmp_path, "empty.csv", ""))
        assert entries == []
        assert meta["header_found"] is False

    def test_banner_only_yields_no_entries(self, tmp_path):
        entries, meta = index.parse_export_csv(_write(tmp_path, "banner.csv", BANNER_EN + "\n"))
        assert entries == []
        assert meta["header_found"] is False

    def test_encoding_fallback_to_cp936(self, tmp_path):
        p = tmp_path / "gbk.csv"
        p.write_bytes(CSV_ZH_WITH_CAPACITY.encode("gbk"))
        entries, meta = index.parse_export_csv(str(p))
        assert len(entries) == 4
        # The banner is Chinese text; recovering the ASCII run inside it proves
        # the code-page fallback decoded the file rather than mojibake'ing it.
        assert "WizTree 4.27" in meta["banner"]
        assert entries[0].size == 1000

    def test_missing_file_raises(self, tmp_path):
        with pytest.raises(FileNotFoundError):
            index.parse_export_csv(str(tmp_path / "nope.csv"))

    def test_meta_reports_columns_and_encoding(self, tmp_path):
        _, meta = index.parse_export_csv(_write(tmp_path, "zh.csv", CSV_ZH_WITH_CAPACITY))
        assert meta["columns"][1] == "大小"
        assert len(meta["columns"]) == 11
        assert meta["encoding"] in ("utf-8-sig", "utf-8")

    def test_utf16_export_is_decoded_not_mojibake(self, tmp_path):
        """Regression: latin-1 accepts any byte sequence, so a UTF-16 file used to
        come back as mojibake with no error at all."""
        p = tmp_path / "utf16.csv"
        p.write_bytes(CSV_EN_PLAIN.encode("utf-16"))
        entries, meta = index.parse_export_csv(str(p))
        assert len(entries) == 4
        assert entries[0].name == "C:\\test\\"
        assert meta["encoding"] in ("utf-16", "utf-16-le", "utf-16-be")
        assert meta["encoding_fallback"] is False

    def test_rows_with_unparseable_size_are_reported_not_silently_dropped(self, tmp_path):
        """Silently dropping rows understates every total; the count is surfaced."""
        text = "\n".join([
            BANNER_EN,
            "File Name,Size,Allocated,Modified,Attributes,Files,Folders",
            '"C:\\x\\",10,10,2026/09/27 11:53:56,0,1,1',
            '"C:\\x\\blank",,10,2026/09/27 11:53:56,0,0,0',
            '"C:\\x\\junk",n/a,10,2026/09/27 11:53:56,0,0,0',
        ])
        entries, meta = index.parse_export_csv(_write(tmp_path, "lossy.csv", text))
        assert len(entries) == 1
        assert meta["skipped_rows"] == [2, 3]
        assert meta["body_rows"] == 3

    def test_clean_file_reports_no_skipped_rows(self, tmp_path):
        _, meta = index.parse_export_csv(_write(tmp_path, "en.csv", CSV_EN_PLAIN))
        assert meta["skipped_rows"] == []
        assert meta["encoding_fallback"] is False

    def test_banner_containing_commas_is_not_adopted_as_header(self, tmp_path):
        """A banner with enough comma fields used to become the header row."""
        text = "\n".join([
            "Generated by WizTree 4.27, build 2026, locale zh-CN",
            "File Name,Size,Allocated,Modified,Attributes,Files,Folders",
            '"C:\\x\\",10,10,2026/09/27 11:53:56,0,1,1',
        ])
        entries, meta = index.parse_export_csv(_write(tmp_path, "banner.csv", text))
        assert len(entries) == 1
        assert meta["columns"][0] == "File Name"
        assert meta["banner"].startswith("Generated by WizTree")


