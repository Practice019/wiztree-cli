class TestSession:

    def test_record_then_history(self):
        s = Session()
        s.record("scan", {"path": "C:\\"}, {"ok": True})
        assert s.history_count == 1
        assert s.history()[0]["command"] == "scan"

    def test_undo_then_redo(self):
        # Matches the upstream CLI-Anything convention: Session returns
        # HistoryEntry objects, and callers use .to_dict() for JSON output.
        s = Session()
        s.record("scan", {}, None)
        assert s.undo().command == "scan"
        assert s.can_redo is True
        assert s.redo().to_dict()["command"] == "scan"
        assert s.can_redo is False

    def test_undo_on_empty_returns_none(self):
        assert Session().undo() is None

    def test_redo_on_empty_returns_none(self):
        assert Session().redo() is None

    def test_record_clears_redo_stack(self):
        s = Session()
        s.record("a", {}, None)
        s.undo()
        s.record("b", {}, None)
        assert s.can_redo is False

    def test_history_limit(self):
        s = Session()
        for i in range(10):
            s.record(f"cmd{i}", {}, None)
        assert len(s.history(limit=3)) == 3

    def test_snapshot_and_restore(self):
        s = Session()
        s.record("scan", {"p": 1}, None)
        snap = s.snapshot()
        s.record("other", {}, None)
        s.restore(snap)
        assert s.history_count == 1

    def test_persist_roundtrip(self, tmp_path):
        path = str(tmp_path / "s.json")
        Session(session_file=path).record("scan", {"p": 1}, {"n": 2})
        reloaded = Session(session_file=path)
        assert reloaded.history_count == 1
        assert reloaded.history(limit=5)[0]["command"] == "scan"

    def test_corrupt_session_file_does_not_crash(self, tmp_path):
        path = tmp_path / "s.json"
        path.write_text("{{{", encoding="utf-8")
        assert Session(session_file=str(path)).history_count == 0


